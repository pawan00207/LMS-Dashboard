/**
 * Generates 115 realistic transactions spread over the past 30 days up to today (2026-11-01)
 */
export function generateSeedTransactions(): Transaction[] {
  const transactions: Transaction[] = [];
  const today = new Date('2026-11-01T10:00:00Z');

  // Let's create transactions across days -30 to 0
  const bookIds = INITIAL_BOOKS.map((b) => b.id);
  const memberIds = INITIAL_MEMBERS.map((m) => m.id);

  let txId = 1;

  for (let daysAgo = 30; daysAgo >= 0; daysAgo--) {
    const txDate = new Date(today.getTime() - daysAgo * 24 * 60 * 60 * 1000);
    const dateStr = txDate.toISOString().split('T')[0];

    // 3 to 5 transactions per day
    const countToday = daysAgo === 0 ? 4 : (daysAgo % 3) + 2;

    for (let c = 0; c < countToday; c++) {
      const bIdx = (txId * 7 + c * 3) % bookIds.length;
      const mIdx = (txId * 5 + c * 2) % memberIds.length;
      const bookId = bookIds[bIdx];
      const memberId = memberIds[mIdx];

      const due = new Date(txDate.getTime() + 14 * 24 * 60 * 60 * 1000);
      const dueDateStr = due.toISOString().split('T')[0];

      let status: 'issued' | 'returned' | 'overdue' = 'returned';
      let returnDateStr: string | null = null;
      let fineAmount = 0;
      let finePaid = true;

      if (daysAgo <= 10) {
        // Recent issues: some returned, some currently issued
        if (c === 0 || daysAgo === 0) {
          status = 'issued';
          returnDateStr = null;
          fineAmount = 0;
          finePaid = false;
        } else {
          // Returned within 2-5 days
          const ret = new Date(txDate.getTime() + (c + 2) * 24 * 60 * 60 * 1000);
          returnDateStr = ret.toISOString().split('T')[0];
          status = 'returned';
        }
      } else if (daysAgo >= 18 && daysAgo <= 28 && c === 1) {
        // Some became OVERDUE!
        if (c === 1 && daysAgo >= 20) {
          // Still not returned -> Overdue!
          status = 'issued'; // active issue but past due
          returnDateStr = null;
          const overdueDays = Math.max(0, Math.ceil((today.getTime() - due.getTime()) / (1000 * 60 * 60 * 24)));
          fineAmount = overdueDays * 5;
          finePaid = false;
        } else {
          // Returned with fine
          const ret = new Date(due.getTime() + (daysAgo % 5 + 1) * 24 * 60 * 60 * 1000);
          returnDateStr = ret.toISOString().split('T')[0];
          status = 'returned';
          const overdueDays = (daysAgo % 5) + 1;
          fineAmount = overdueDays * 5;
          finePaid = daysAgo % 2 === 0; // some paid, some unpaid
        }
      } else {
        // Returned on time
        const ret = new Date(txDate.getTime() + (8 + (c % 5)) * 24 * 60 * 60 * 1000);
        returnDateStr = ret.toISOString().split('T')[0];
        status = 'returned';
        fineAmount = 0;
        finePaid = true;
      }

      transactions.push({
        id: `tx_${String(txId).padStart(4, '0')}`,
        book_id: bookId,
        member_id: memberId,
        issued_by: 'Librarian Clara Oswald',
        issue_date: dateStr,
        due_date: dueDateStr,
        return_date: returnDateStr,
        status: status,
        fine_amount: fineAmount,
        fine_paid: finePaid,
        notes: fineAmount > 0 ? `Late return fine accrued: ₹${fineAmount}` : undefined,
      });

      txId++;
    }
  }

  // Ensure Eleanor Vance (demo member MEM-1001) has 2 active books: one on-time, one due soon, and past history
  transactions.push({
    id: `tx_${String(txId++).padStart(4, '0')}`,
    book_id: 'bk_001', // Atomic Habits
    member_id: 'mem_001',
    issued_by: 'Librarian Clara Oswald',
    issue_date: '2026-10-24',
    due_date: '2026-11-07',
    return_date: null,
    status: 'issued',
    fine_amount: 0,
    fine_paid: false,
    notes: 'Renewed once online',
  });

  transactions.push({
    id: `tx_${String(txId++).padStart(4, '0')}`,
    book_id: 'bk_004', // Meditations
    member_id: 'mem_001',
    issued_by: 'Arthur Pendelton',
    issue_date: '2026-10-28',
    due_date: '2026-11-11',
    return_date: null,
    status: 'issued',
    fine_amount: 0,
    fine_paid: false,
  });

  return transactions;
}

